import { stripTypeScriptTypes } from 'node:module';
import fs from 'node:fs';
import path from 'node:path';

function stripImportsAndExports(code: string): string {
  // Strip import statements (single or multiline)
  let clean = code.replace(/import[\s\S]*?from\s*[\x27\x22][^\x27\x22]+[\x27\x22]\s*;?/g, '');
  clean = clean.replace(/import\s*[\x27\x22][^\x27\x22]+[\x27\x22]\s*;?/g, '');
  // Strip export { ... }
  clean = clean.replace(/export\s*\{[\s\S]*?\}\s*;?/g, '');
  // Strip export default
  clean = clean.replace(/export\s+default\s+/g, '');
  // Strip export async function / export function / export class / export const / export let / export var
  clean = clean.replace(/export\s+(async\s+)?(function\*?|class|const|let|var)\s+/g, '$1$2 ');
  return clean;
}

function build(): void {
  const rootDir = process.cwd();
  const distDir = path.join(rootDir, 'dist');
  fs.mkdirSync(distDir, { recursive: true });

  const sourceFiles = [
    'src/types/wiki.ts',
    'src/lib/frontmatter.ts',
    'src/lib/schema-parser.ts',
    'src/lib/markdown-tables.ts',
    'src/lib/human-actions.ts',
    'src/lib/graph-builder.ts',
    'src/ui/graph-canvas.ts',
    'src/ui/app-controller.ts',
  ];

  let bundleParts: string[] = [
    '// Codebase Wiki Desktop App Bundle',
    '// Generated by scripts/build-ui.ts',
    '(function () {',
  ];

  for (const relPath of sourceFiles) {
    const fullPath = path.join(rootDir, relPath);
    if (!fs.existsSync(fullPath)) {
      throw new Error(`Source file not found: ${fullPath}`);
    }
    const rawContent = fs.readFileSync(fullPath, 'utf-8');
    const strippedTypes = stripTypeScriptTypes(rawContent);
    const cleaned = stripImportsAndExports(strippedTypes);

    bundleParts.push(`\n// --- Start: ${relPath} ---`);
    bundleParts.push(cleaned);
    bundleParts.push(`// --- End: ${relPath} ---\n`);
  }

  // Auto-instantiate AppController on DOMContentLoaded
  bundleParts.push(`
  if (typeof window !== 'undefined') {
    window.addEventListener('DOMContentLoaded', () => {
      window.app = new AppController();
    });
  }
})();
`);

  const bundleJs = bundleParts.join('\n');
  const bundlePath = path.join(distDir, 'app.js');
  fs.writeFileSync(bundlePath, bundleJs, 'utf-8');
  console.log(`[build-ui] Wrote ${bundlePath} (${(bundleJs.length / 1024).toFixed(1)} KB)`);

  // Build standalone run-human-action.mjs in resources/
  const humanActionFiles = [
    'src/types/wiki.ts',
    'src/lib/frontmatter.ts',
    'src/lib/schema-parser.ts',
    'src/lib/markdown-tables.ts',
    'src/lib/human-actions.ts',
  ];
  let humanActionParts: string[] = [
    '// Codebase Wiki Human Action Runner',
    '// Generated by scripts/build-ui.ts',
    'import fs from "node:fs";',
  ];
  for (const relPath of humanActionFiles) {
    const fullPath = path.join(rootDir, relPath);
    const rawContent = fs.readFileSync(fullPath, 'utf-8');
    const strippedTypes = stripTypeScriptTypes(rawContent);
    const cleaned = stripImportsAndExports(strippedTypes);
    humanActionParts.push(`\n// --- Start: ${relPath} ---`);
    humanActionParts.push(cleaned);
    humanActionParts.push(`// --- End: ${relPath} ---\n`);
  }
  humanActionParts.push(`
try {
  const input = JSON.parse(fs.readFileSync(0, "utf-8"));
  let result;
  if (input.action === "promote-proposal") {
    result = promoteProposalToOpen(input);
  } else if (input.action === "close-unproven") {
    result = closeTrackerItemHumanUnproven(input);
  } else if (input.action === "approve-decision") {
    result = approveDecisionHuman(input);
  } else {
    throw new Error("Unknown action: " + input.action);
  }
  process.stdout.write(JSON.stringify(result));
} catch (err) {
  process.stderr.write(String(err.message || err));
  process.exit(1);
}
`);
  const humanActionJs = humanActionParts.join('\n');
  const resourcesDir = path.join(rootDir, 'resources');
  fs.mkdirSync(resourcesDir, { recursive: true });
  const runnerPath = path.join(resourcesDir, 'run-human-action.mjs');
  fs.writeFileSync(runnerPath, humanActionJs, 'utf-8');
  console.log(`[build-ui] Wrote ${runnerPath} (${(humanActionJs.length / 1024).toFixed(1)} KB)`);

  // Copy styles.css
  const srcCss = path.join(rootDir, 'src/ui/styles.css');
  const distCss = path.join(distDir, 'styles.css');
  fs.copyFileSync(srcCss, distCss);
  console.log(`[build-ui] Copied ${srcCss} -> ${distCss}`);

  // Copy index.html
  const srcHtml = path.join(rootDir, 'index.html');
  const distHtml = path.join(distDir, 'index.html');
  fs.copyFileSync(srcHtml, distHtml);
  console.log(`[build-ui] Copied ${srcHtml} -> ${distHtml}`);

  console.log('[build-ui] Build complete!');
}

build();
